-- Печатный артикул исполнения (как в прайсе и на этикетке).
--
-- Обычно он собирается из артикула изделия и кода исполнения через дефис:
--   А.3776.001 + 02.02 → А.3776.001-02.02
-- Но у части семейств цвет входит в обозначение через точку, и склейка
-- через дефис даёт неверный артикул:
--   А.3731.023 (изделие) + 1-01.00-150 → нужно А.3731.023.1-01.00-150
-- Поэтому артикул можно хранить явно; пусто — собирается автоматически.
ALTER TABLE component_modifications ADD COLUMN IF NOT EXISTS full_article VARCHAR(150);
